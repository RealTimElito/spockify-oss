#!/usr/bin/env bash
# Fail closed when a production profile is requested with placeholder secrets.
# Invoked by docker/run.sh when SPOCKIFY_PRODUCTION=1 or SPOCKIFY_PROFILE=production.
set -euo pipefail

production_requested() {
  [[ "${SPOCKIFY_PRODUCTION:-}" == "1" ]] || [[ "${SPOCKIFY_PROFILE:-}" == "production" ]]
}

if ! production_requested; then
  exit 0
fi

fail() {
  echo "SPOCKIFY production profile refused: $*" >&2
  exit 1
}

PLACEHOLDERS=(
  "spockify-dev"
  "sk-spockify-change-me"
  "change-me-to-at-least-32-characters"
  "change-me-searxng-secret"
)

check_placeholder() {
  local name="$1" value="${2:-}"
  local p
  if [[ -z "${value}" ]]; then
    fail "${name} is empty"
  fi
  for p in "${PLACEHOLDERS[@]}"; do
    if [[ "${value}" == "${p}" ]]; then
      fail "${name} is a documented placeholder (${p})"
    fi
  done
}

check_placeholder POSTGRES_PASSWORD "${POSTGRES_PASSWORD:-}"
check_placeholder LITELLM_MASTER_KEY "${LITELLM_MASTER_KEY:-}"
check_placeholder WEBUI_SECRET_KEY "${WEBUI_SECRET_KEY:-}"
check_placeholder SEARXNG_SECRET "${SEARXNG_SECRET:-}"

if [[ "${#WEBUI_SECRET_KEY}" -lt 32 ]]; then
  fail "WEBUI_SECRET_KEY must be at least 32 characters"
fi

if [[ "${ENABLE_SIGNUP:-true}" == "true" ]]; then
  fail "ENABLE_SIGNUP must be false for the production profile"
fi

loopback_bind() {
  case "${1:-}" in
    127.0.0.1|localhost|::1) return 0 ;;
    *) return 1 ;;
  esac
}

API_BIND="${SPOCKIFY_API_BIND:-0.0.0.0}"
ROUTER_BIND="${SPOCKIFY_ROUTER_BIND:-0.0.0.0}"
if ! loopback_bind "${API_BIND}"; then
  fail "SPOCKIFY_API_BIND must be 127.0.0.1 for the production profile (got ${API_BIND})"
fi
if ! loopback_bind "${ROUTER_BIND}"; then
  fail "SPOCKIFY_ROUTER_BIND must be 127.0.0.1 for the production profile (got ${ROUTER_BIND})"
fi

ISO="$(printf '%s' "${SPOCKIFY_ISOLATED_RUNNER:-}" | tr '[:upper:]' '[:lower:]')"
case "${ISO}" in
  1|true|yes|on|bwrap|podman) ;;
  *)
    fail "SPOCKIFY_ISOLATED_RUNNER must be bwrap or podman for the production profile"
    ;;
esac

is_digest() {
  [[ "${1:-}" == *@sha256:* ]]
}

is_local_build() {
  case "${1:-}" in
    *:local|spockify-router:local|spockify-openwebui:local) return 0 ;;
    *) return 1 ;;
  esac
}

refuse_unpinned_latest() {
  local name="$1" value="$2"
  if [[ "${value}" == *:latest ]] && ! is_digest "${value}"; then
    fail "${name} must not be an unpinned :latest tag for the production profile (got ${value}). Record a digest with docker/record-image-digests.sh"
  fi
}

POSTGRES_IMAGE="${SPOCKIFY_POSTGRES_IMAGE:-postgres:17-alpine}"
SEARXNG_IMAGE="${SPOCKIFY_SEARXNG_IMAGE:-docker.io/searxng/searxng:latest}"
OLLAMA_IMAGE="${SPOCKIFY_OLLAMA_IMAGE:-docker.io/ollama/ollama:latest}"
LITELLM_IMAGE="${SPOCKIFY_LITELLM_IMAGE:-ghcr.io/berriai/litellm:main-v1.79.3-stable}"
ROUTER_IMAGE="${SPOCKIFY_ROUTER_IMAGE:-spockify-router:local}"
OWUI_IMAGE="${SPOCKIFY_OPENWEBUI_IMAGE:-spockify-openwebui:local}"

refuse_unpinned_latest SPOCKIFY_POSTGRES_IMAGE "${POSTGRES_IMAGE}"
refuse_unpinned_latest SPOCKIFY_SEARXNG_IMAGE "${SEARXNG_IMAGE}"
refuse_unpinned_latest SPOCKIFY_OLLAMA_IMAGE "${OLLAMA_IMAGE}"
refuse_unpinned_latest SPOCKIFY_LITELLM_IMAGE "${LITELLM_IMAGE}"
refuse_unpinned_latest SPOCKIFY_ROUTER_IMAGE "${ROUTER_IMAGE}"
refuse_unpinned_latest SPOCKIFY_OPENWEBUI_IMAGE "${OWUI_IMAGE}"

# Published GHCR/router images must be digest-pinned. Tree :local builds are the
# workstation exception so a production-profile smoke can still build from git.
if ! is_local_build "${ROUTER_IMAGE}" && ! is_digest "${ROUTER_IMAGE}"; then
  fail "SPOCKIFY_ROUTER_IMAGE must be image@sha256:… (or :local for a tree build); got ${ROUTER_IMAGE}"
fi
if ! is_local_build "${OWUI_IMAGE}" && ! is_digest "${OWUI_IMAGE}"; then
  fail "SPOCKIFY_OPENWEBUI_IMAGE must be image@sha256:… (or :local for a tree build); got ${OWUI_IMAGE}"
fi

# Host CLI/IDE read process.env, not compose container env (G1-13).
# Export the same isolation flags the harness mergeHostIsolationEnv() loads.
case "${ISO}" in
  podman) HOST_ISO_RUNNER=podman ;;
  *) HOST_ISO_RUNNER=bwrap ;;
esac
HOST_ISO="${SPOCKIFY_HOST_ISOLATION_ENV:-}"
if [[ -z "${HOST_ISO}" ]]; then
  HOST_ISO="${XDG_CONFIG_HOME:-${HOME:-}/.config}/spockify/isolation.env"
fi
if [[ -z "${HOST_ISO}" || "${HOST_ISO}" == "/.config/spockify/isolation.env" ]]; then
  fail "cannot export host isolation env (set SPOCKIFY_HOST_ISOLATION_ENV or HOME)"
fi
HOST_ISO_DIR="$(dirname "${HOST_ISO}")"
mkdir -p "${HOST_ISO_DIR}" || fail "cannot create ${HOST_ISO_DIR} for host isolation env"
umask 077
cat > "${HOST_ISO}" <<EOF
# Generated by docker/check-production-secrets.sh for host CLI/IDE shells.
# Isolation flags only. Process environment overrides these keys.
SPOCKIFY_PRODUCTION=1
SPOCKIFY_ISOLATED_RUNNER=${HOST_ISO_RUNNER}
EOF
if [[ ! -s "${HOST_ISO}" ]]; then
  fail "cannot write host isolation env ${HOST_ISO}"
fi

echo "production secret check: ok"
